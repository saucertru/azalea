/** Resize an image File to a Blob (keeps GIFs as-is so they stay animated). */
export async function resizeImage(file, maxW, maxH, quality = 0.88) {
  if (file.type === 'image/gif') return file;
  const url = URL.createObjectURL(file);
  try {
    const img = await new Promise((res, rej) => {
      const i = new Image();
      i.onload = () => res(i);
      i.onerror = rej;
      i.src = url;
    });
    const scale = Math.min(1, maxW / img.width, maxH / img.height);
    const c = document.createElement('canvas');
    c.width = Math.round(img.width * scale);
    c.height = Math.round(img.height * scale);
    c.getContext('2d').drawImage(img, 0, 0, c.width, c.height);
    return await new Promise((res) => c.toBlob(res, 'image/webp', quality));
  } finally {
    URL.revokeObjectURL(url);
  }
}

export function blobToDataUrl(blob) {
  return new Promise((res, rej) => {
    const r = new FileReader();
    r.onload = () => res(r.result);
    r.onerror = rej;
    r.readAsDataURL(blob);
  });
}

export function pickFile(accept) {
  return new Promise((resolve) => {
    const inp = h('input', { type: 'file', accept, style: { display: 'none' } });
    inp.addEventListener('change', () => {
      resolve(inp.files[0] || null);
      inp.remove();
    });
    document.body.append(inp);
    inp.click();
  });
}

export function avatarEl(profile, size = 36) {
  const name = profile?.username || '?';
  const el = h('div', { class: 'avatar', style: { width: `${size}px`, height: `${size}px`, fontSize: `${Math.round(size * 0.42)}px` } });
  if (profile?.avatar_url) el.append(h('img', { src: profile.avatar_url, alt: '', loading: 'lazy' }));
  else el.textContent = name[0].toUpperCase();
  return el;
}

